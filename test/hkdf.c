static const struct tc Tc[] = {
  { "1", ikm1, sizeof (ikm1), salt1, sizeof (salt1), info1, sizeof (info1), sizeof (okm1), prk1, okm1 }
 ,{ "2", ikm2, sizeof (ikm2), salt2, sizeof (salt2), info2, sizeof (info2), sizeof (okm2), prk2, okm2 }
 ,{ "3", ikm1, sizeof (ikm1), 0,     0,              0,     0,              sizeof (okm3), prk3, okm3 }
};

int
main(
  void
){
  unsigned int i;
  int fail;

  fail = 0;
  for (i = 0; i < sizeof (Tc) / sizeof (Tc[0]); ++i) {
    const struct tc *t;
    unsigned char prk[SHA256_SZ];
    unsigned char okm[255 * SHA256_SZ];
    int bad;

    bad = 0;
    t = &Tc[i];
    sha256hmac(t->salt, t->saltl, t->ikm, t->ikml, prk); /* hmac is hkdf extract */
    if (memcmp(prk, t->prk, SHA256_SZ)) {
      printf("case %s: PRK MISMATCH\n", t->name);
      bad = 1;
    }
    sha256hkdf(prk, SHA256_SZ, t->info, t->infol, okm, t->okml);
    if (memcmp(okm, t->okm, t->okml)) {
      printf("case %s: OKM MISMATCH\n", t->name);
      bad = 1;
    }
    if (bad)
      fail = 1;
    else
      printf("case %s: ok\n", t->name);
  }
  printf("%s\n", fail ? "FAIL" : "PASS");
  return (fail);
}
